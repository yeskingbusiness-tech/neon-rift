/* Build-time weapon facts for the server — parses WEAPON_BLUEPRINTS out of game.js so the
   anti-cheat can gate fire cadence per claimed weapon index. Blueprint rows are packed arrays:
   name, slot, auto, dmg, rpm, mag, reserve, spread… (rpm = blueprint field 4).               */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const src = fs.readFileSync(path.join(ROOT, 'game.js'), 'utf8');
const start = src.indexOf('const WEAPON_BLUEPRINTS');
if (start < 0) throw new Error('WEAPON_BLUEPRINTS not found in game.js');
const open = src.indexOf('[', start);
let depth = 0, end = -1;
for (let i = open; i < src.length; i++){ if (src[i] === '[') depth++; else if (src[i] === ']'){ depth--; if (!depth){ end = i + 1; break; } } }

// eval the literal array — it is plain data by construction
const blueprints = eval(src.slice(open, end));
if (!Array.isArray(blueprints) || !blueprints.length) throw new Error('WEAPON_BLUEPRINTS parse failed');
const rpm = blueprints.map(b => b && b.length > 4 ? b[4] : 0);

const out = { count: blueprints.length, rpm, note: 'generated by scripts/gen-weapon-table.js — rebuild with npm run build' };
fs.writeFileSync(path.join(ROOT, 'weapon-table.json'), JSON.stringify(out));
console.log(`[build] weapon-table.json: ${out.count} weapons, rpm range ${Math.min(...rpm)}–${Math.max(...rpm)}`);
